// CGEventFlags for the modifiers.
var macFlag = map[uint16]uint64{
	0x11: 1 << 18, // control
	0x10: 1 << 17, // shift
	0x12: 1 << 19, // option
	0x5B: 1 << 20, // command
}

// NX_KEYTYPE media keys.
var macMedia = map[uint16]int{
	0xAF: 0, 0xAE: 1, 0xAD: 7, 0xB3: 16, 0xB0: 17, 0xB1: 18,
}

type macActuator struct{}

var macMods struct {
	mu    sync.Mutex
	flags uint64
}

func (macActuator) Key(vk uint16, down bool) {
	if m, ok := macMedia[vk]; ok {
		C.macMediaKey(C.int(m), b2i(down))
		return
	}
	switch vk { // browser back / forward
	case 0xA6:
		if down {
			tapMac("Cmd+[")
		}
		return
	case 0xA7:
		if down {
			tapMac("Cmd+]")
		}
		return
	}
	code, ok := macKeycodes[vk]
	if !ok {
		logf("mac: no key for VK %02X", vk)
		return
	}
	macMods.mu.Lock()
	if f, isMod := macFlag[vk]; isMod {
		if down {
			macMods.flags |= f
		} else {
			macMods.flags &^= f
		}
	}
	flags := macMods.flags
	macMods.mu.Unlock()
	C.macKey(C.int(code), b2i(down), C.uint64_t(flags))
}

func tapMac(s string) {
	if k, err := ParseKeys(s); err == nil {
		tapCombo(macActuator{}, k)
	}
}

func (macActuator) MouseButton(btn string, down bool) {
	n := map[string]int{"left": 0, "right": 1, "middle": 2, "back": 3, "forward": 4}[btn]
	C.macMouseButton(C.int(n), b2i(down))
}

func (macActuator) Wheel(delta int, horizontal bool) {
	px := delta / 4 // 120 per notch on Windows -> 30 pixels
	if px == 0 {
		if delta > 0 {
			px = 1
		} else if delta < 0 {
			px = -1
		}
	}
	if horizontal {
		C.macScroll(0, C.int(-px)) // macOS: positive is left
	} else {
		C.macScroll(C.int(px), 0)
	}
}

func (macActuator) Run(target string) {
	t := strings.Trim(target, `"`)
	if strings.HasSuffix(strings.ToLower(t), ".app") && !strings.Contains(t, "/") {
		_ = exec.Command("open", "-a", t).Start()
		return
	}
	_ = exec.Command("open", t).Start()
}
